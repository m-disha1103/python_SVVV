#WAP to demonstrate string slicing
s="hey how are you guys !!!"
print(s[7:17])      #output: how are you
print(s[:5])        #output: hey how
print(s[:7]+s[7:])  #output: hey how are you guys
print(s[-9:-4:1]) #output: guys
print(s[4:-3]) #output: how are you guys (length of string will be 17)